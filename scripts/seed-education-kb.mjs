async function main() {
  await sql.unsafe(CREATE);
  let inserted = 0;
  for (const [stage, category, region, title, question, content, keywords, source] of ENTRIES) {
    await sql`
      INSERT INTO education_kb (stage, category, region, title, question, content, keywords, source)
      VALUES (${stage}, ${category}, ${region}, ${title}, ${question}, ${content}, ${keywords}, ${source})
      ON CONFLICT (stage, title) DO UPDATE SET
        category = EXCLUDED.category,
        region = EXCLUDED.region,
        question = EXCLUDED.question,
        content = EXCLUDED.content,
        keywords = EXCLUDED.keywords,
        source = EXCLUDED.source,
        _updated_at = now()
    `;
    inserted++;
  }
  const [{ count }] = await sql`SELECT count(*)::int AS count FROM education_kb`;
  console.log(`education_kb 种子完成：本次处理 ${inserted} 条，库内共 ${count} 条。`);
  await sql.end();
}

main().catch((error) => {
  console.error('种子失败：', error.message);
  process.exit(1);
});
